#!/usr/bin/env python3
"""Generate pixel-identical WebP copies for hosting; keep all source PNGs intact.

Run from any directory with: python scripts/optimize-art.py
Requires Node.js and Pillow with WebP support only when regenerating artwork.
The generated files are retained, so running/building the game does not need
Python or Pillow.
"""

import hashlib
import json
import re
import subprocess
from concurrent.futures import ThreadPoolExecutor
from io import BytesIO
from pathlib import Path

from PIL import Image, features


ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "public" / "optimized"


def optimize_asset(item):
    key, filename, previous = item
    if not re.fullmatch(r"[A-Za-z][A-Za-z0-9]*", key):
        raise ValueError(f"Unsafe asset key: {key!r}")
    if Path(filename).name != filename:
        raise ValueError(f"Source must be an image filename: {filename!r}")
    source = ROOT / "public" / "graphics" / filename
    source_data = source.read_bytes()
    source_sha = hashlib.sha256(source_data).hexdigest()
    if previous and previous.get("sourceSha256") == source_sha and previous.get("source") == filename:
        old_name = previous.get("file", "")
        old_path = OUTPUT / old_name
        if Path(old_name).name == old_name and old_name.endswith(".webp") and old_path.is_file():
            if hashlib.sha256(old_path.read_bytes()).hexdigest() == previous.get("optimizedSha256"):
                return key, previous
    with Image.open(BytesIO(source_data)) as original:
        image = original.convert("RGBA")
        options = {"format": "WEBP", "lossless": True, "exact": True, "method": 4}
        if original.info.get("icc_profile"):
            options["icc_profile"] = original.info["icc_profile"]
        encoded = BytesIO()
        image.save(encoded, **options)
        optimized_data = encoded.getvalue()
        with Image.open(BytesIO(optimized_data)) as reopened:
            decoded = reopened.convert("RGBA")
            if decoded.size != image.size or decoded.tobytes() != image.tobytes():
                raise RuntimeError(f"Lossless pixel verification failed: {filename}")
        width, height = image.size

    # Write only after verifying all pixels, including RGB beneath zero alpha.
    optimized_sha = hashlib.sha256(optimized_data).hexdigest()
    destination = OUTPUT / f"{key}-{optimized_sha[:12]}.webp"
    temporary = destination.with_suffix(".webp.tmp")
    temporary.write_bytes(optimized_data)
    temporary.replace(destination)
    return key, {
        "file": destination.name,
        "source": filename,
        "sourceSha256": source_sha,
        "optimizedSha256": optimized_sha,
        "bytes": len(optimized_data),
        "sourceBytes": len(source_data),
        "width": width,
        "height": height,
    }


def main():
    if not features.check("webp"):
        raise RuntimeError("Pillow must include WebP encoding support")
    registry = subprocess.run(
        [
            "node", "--input-type=module", "--eval",
            "import { ASSET_FILES } from './src/assets.js'; "
            "process.stdout.write(JSON.stringify(ASSET_FILES));",
        ],
        cwd=ROOT, check=True, capture_output=True, text=True,
    )
    assets = json.loads(registry.stdout)
    OUTPUT.mkdir(parents=True, exist_ok=True)
    previous_manifest_path = OUTPUT / "manifest.json"
    previous_manifest = (
        json.loads(previous_manifest_path.read_text(encoding="utf-8"))
        if previous_manifest_path.exists() else {}
    )
    with ThreadPoolExecutor(max_workers=2) as pool:
        manifest = dict(pool.map(optimize_asset, ((key, filename, previous_manifest.get(key))
                                                for key, filename in assets.items())))
    generated_registry = {
        key: {name: item[name] for name in ["file", "sourceSha256", "optimizedSha256"]}
        for key, item in manifest.items()
    }
    registry_path = ROOT / "src" / "optimized-art.js"
    registry_temporary = registry_path.with_suffix(".js.tmp")
    registry_temporary.write_text(
        "// Generated by scripts/optimize-art.py; preserve the uploaded source PNGs.\n"
        "export const OPTIMIZED_ART = " + json.dumps(generated_registry, indent=2) + ";\n",
        encoding="utf-8",
    )
    registry_temporary.replace(registry_path)
    temporary = OUTPUT / "manifest.json.tmp"
    temporary.write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    temporary.replace(OUTPUT / "manifest.json")
    current_files = {item["file"] for item in manifest.values()}
    for item in previous_manifest.values():
        old_file = item.get("file", "")
        if old_file and Path(old_file).name == old_file and old_file.endswith(".webp") and old_file not in current_files:
            (OUTPUT / old_file).unlink(missing_ok=True)
    original_bytes = sum(item["sourceBytes"] for item in manifest.values())
    optimized_bytes = sum(item["bytes"] for item in manifest.values())
    print(json.dumps({
        "assets": len(manifest), "originalBytes": original_bytes,
        "optimizedBytes": optimized_bytes,
        "savedBytes": original_bytes - optimized_bytes,
        "savedPercent": round(100 * (1 - optimized_bytes / original_bytes), 1),
        "decodedPixels": "identical", "sourcePNGs": "unchanged",
    }))


if __name__ == "__main__":
    main()
